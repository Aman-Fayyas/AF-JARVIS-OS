from pathlib import Path
import os
import re
import stat
import sys
path = Path(sys.argv[1])
fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
with os.fdopen(fd) as stream:
    info = os.fstat(stream.fileno())
    if not stat.S_ISREG(info.st_mode) or info.st_mode & 0o077 or info.st_size > 512:
        raise SystemExit('Password hash must be a private regular file (chmod 600).')
    value = stream.read().strip()
if not re.fullmatch(r'\$6\$(?:rounds=\d+\$)?[./A-Za-z0-9]{1,16}\$[./A-Za-z0-9]{86}', value):
    raise SystemExit('Expected a SHA-512 crypt password hash generated by openssl passwd -6.')
